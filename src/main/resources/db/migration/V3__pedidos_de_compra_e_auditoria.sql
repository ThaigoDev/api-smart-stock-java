-- Pedidos de compra (alerta de reposição → pedido → recebimento) e autoria das movimentações.

-- quem registrou cada movimentação ("sistema" para lançamentos automáticos)
ALTER TABLE movimentacao_estoque ADD COLUMN registrado_por character varying(255);

CREATE TABLE pedido_compra (
    id            uuid NOT NULL,
    numero        bigint GENERATED BY DEFAULT AS IDENTITY,
    fornecedor_id uuid NOT NULL,
    status        character varying(255) NOT NULL,
    observacao    character varying(255),
    criado_por    character varying(255),
    criado_em     timestamp(6) without time zone,
    recebido_por  character varying(255),
    recebido_em   timestamp(6) without time zone,
    cancelado_em  timestamp(6) without time zone,
    CONSTRAINT pedido_compra_pkey PRIMARY KEY (id),
    CONSTRAINT uk_pedido_compra_numero UNIQUE (numero),
    CONSTRAINT pedido_compra_status_check CHECK (status IN ('ABERTO', 'RECEBIDO', 'CANCELADO')),
    CONSTRAINT fk_pedido_compra_fornecedor FOREIGN KEY (fornecedor_id) REFERENCES fornecedor (id)
);

CREATE INDEX idx_pedido_compra_status ON pedido_compra (status);

CREATE TABLE item_pedido_compra (
    id         uuid    NOT NULL,
    pedido_id  uuid    NOT NULL,
    produto_id uuid    NOT NULL,
    quantidade integer NOT NULL,
    CONSTRAINT item_pedido_compra_pkey PRIMARY KEY (id),
    CONSTRAINT item_pedido_compra_quantidade_check CHECK (quantidade > 0),
    -- um produto aparece uma única vez em cada pedido
    CONSTRAINT uk_item_pedido_produto UNIQUE (pedido_id, produto_id),
    CONSTRAINT fk_item_pedido_compra_pedido  FOREIGN KEY (pedido_id)  REFERENCES pedido_compra (id),
    CONSTRAINT fk_item_pedido_compra_produto FOREIGN KEY (produto_id) REFERENCES produto (id)
);
