-- Esquema inicial do Smart Stock.
-- Novas alterações de estrutura devem entrar em novos arquivos (V2__..., V3__...), nunca editando este.

-- ------------------------------------------------------------------ segurança

CREATE TABLE usuario (
    id    uuid NOT NULL,
    email character varying(255),
    nome  character varying(255),
    senha character varying(255),
    CONSTRAINT usuario_pkey PRIMARY KEY (id)
);

CREATE TABLE funcao (
    funcao_id bigint GENERATED BY DEFAULT AS IDENTITY,
    nome      character varying(255),
    create_at timestamp(6) without time zone,
    update_at timestamp(6) without time zone,
    CONSTRAINT funcao_pkey PRIMARY KEY (funcao_id)
);

CREATE TABLE funcoes_usuario (
    funcao_id  bigint NOT NULL,
    usuario_id uuid   NOT NULL,
    CONSTRAINT funcoes_usuario_pkey PRIMARY KEY (funcao_id, usuario_id),
    CONSTRAINT fk_funcoes_usuario_funcao  FOREIGN KEY (funcao_id)  REFERENCES funcao (funcao_id),
    CONSTRAINT fk_funcoes_usuario_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE TABLE cliente_seguranca (
    id                   uuid NOT NULL,
    cliente_id           character varying(255),
    cliente_senha        character varying(255),
    scopes               character varying(255),
    url_redirecionamento character varying(255),
    CONSTRAINT cliente_seguranca_pkey PRIMARY KEY (id)
);

-- ------------------------------------------------------------------ cadastros

CREATE TABLE categoria (
    id                 uuid NOT NULL,
    nome               character varying(255),
    descricao          character varying(255),
    criado_em          timestamp(6) without time zone,
    ultima_atualizacao timestamp(6) without time zone,
    CONSTRAINT categoria_pkey PRIMARY KEY (id)
);

CREATE TABLE fornecedor (
    id                 uuid NOT NULL,
    nome               character varying(255),
    email              character varying(255),
    telefone           character varying(255),
    criado_em          timestamp(6) without time zone,
    ultima_atualizacao timestamp(6) without time zone,
    CONSTRAINT fornecedor_pkey PRIMARY KEY (id)
);

CREATE TABLE produto (
    id                   uuid    NOT NULL,
    nome                 character varying(255),
    sku                  character varying(255),
    preco                numeric(38, 0),
    estoque_minimo       integer,
    estoque_maximo       integer,
    prazo_reposicao_dias integer,
    ativo                boolean,
    categoria_id         uuid    NOT NULL,
    fornecedor_id        uuid    NOT NULL,
    CONSTRAINT produto_pkey PRIMARY KEY (id),
    CONSTRAINT fk_produto_categoria  FOREIGN KEY (categoria_id)  REFERENCES categoria (id),
    CONSTRAINT fk_produto_fornecedor FOREIGN KEY (fornecedor_id) REFERENCES fornecedor (id)
);

-- ------------------------------------------------------------------ estoque

-- saldo atual de cada produto (um registro por produto)
CREATE TABLE estoque (
    id                 uuid NOT NULL,
    produto_id         uuid,
    quantidade         integer,
    ultima_sequencia   bigint,
    criado_em          timestamp(6) without time zone,
    ultima_atualizacao timestamp(6) without time zone,
    CONSTRAINT estoque_pkey PRIMARY KEY (id),
    CONSTRAINT estoque_produto_id_key UNIQUE (produto_id),
    CONSTRAINT fk_estoque_produto FOREIGN KEY (produto_id) REFERENCES produto (id)
);

-- histórico imutável (kardex): toda alteração de saldo é um registro aqui
CREATE TABLE movimentacao_estoque (
    id                     uuid    NOT NULL,
    produto_id             uuid    NOT NULL,
    tipo                   character varying(255),
    quantidade             integer,
    motivo                 character varying(255),
    data_movimentacao      timestamp(6) without time zone,
    criado_em              timestamp(6) without time zone,
    saldo_anterior         integer,
    saldo_posterior        integer,
    sequencia              bigint,
    estornada              boolean DEFAULT false NOT NULL,
    movimentacao_origem_id uuid,
    CONSTRAINT movimentacao_estoque_pkey PRIMARY KEY (id),
    CONSTRAINT movimentacao_estoque_tipo_check
        CHECK (tipo IN ('ENTRADA', 'SAIDA', 'DEVOLUCAO', 'AJUSTE', 'ESTORNO')),
    -- duas movimentações nunca ocupam a mesma posição no histórico do produto
    CONSTRAINT uk_movimentacao_produto_sequencia UNIQUE (produto_id, sequencia),
    CONSTRAINT fk_movimentacao_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT fk_movimentacao_origem  FOREIGN KEY (movimentacao_origem_id) REFERENCES movimentacao_estoque (id)
);

CREATE INDEX idx_movimentacao_produto_data ON movimentacao_estoque (produto_id, data_movimentacao);
