package com.thai.finance.api.finance.api.domain.entities;

import com.thai.finance.api.finance.api.domain.enums.StatusPedidoCompra;
import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.annotations.Generated;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

/**
 * Pedido de compra a um fornecedor. Ao ser recebido, gera uma ENTRADA no estoque para cada item,
 * todas na mesma transação: ou o pedido inteiro entra no estoque, ou nada entra.
 */
@Entity
@Table(name = "pedido_compra")
@Getter
@Setter
@EntityListeners(AuditingEntityListener.class)
public class PedidoCompra {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    // número sequencial legível (PC-000001), gerado pelo banco
    @Generated
    @Column(nullable = false, insertable = false, updatable = false, columnDefinition = "bigint generated by default as identity")
    private Long numero;

    @ManyToOne(optional = false)
    @JoinColumn(nullable = false)
    private Fornecedor fornecedor;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private StatusPedidoCompra status = StatusPedidoCompra.ABERTO;

    private String observacao;

    private String criado_por;

    @CreatedDate
    private LocalDateTime criado_em;

    private String recebido_por;

    private LocalDateTime recebido_em;

    private LocalDateTime cancelado_em;

    @OneToMany(mappedBy = "pedido", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<ItemPedidoCompra> itens = new ArrayList<>();

    public void adicionarItem(Produto produto, int quantidade) {
        ItemPedidoCompra item = new ItemPedidoCompra();
        item.setPedido(this);
        item.setProduto(produto);
        item.setQuantidade(quantidade);
        itens.add(item);
    }

    public String codigo() {
        return numero == null ? null : String.format("PC-%06d", numero);
    }
}
